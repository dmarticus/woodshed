import { mkdtempSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomUUID } from "node:crypto";
import { command } from "../src/command";
import { publishedPrices } from "../src/usage";
import { gitEnvironment } from "../src/git-environment";
import { workerCommand } from "../src/worker-credentials";

const config = await Bun.file(process.argv[2]).json();
if (!config.gitSigningKey) throw new Error("Complete setup-signing before running this smoke test");
process.env.WOODSHED_SIGNING_KEY = config.gitSigningKey;
const directory = mkdtempSync(join(tmpdir(), "woodshed-access-"));
const resultDirectory = join(directory, "result"); mkdirSync(resultDirectory);
await command(["git", "init", "-q"], { cwd: directory });
await command(["git", "config", "user.name", "Woodshed access test"], { cwd: directory });
await command(["git", "config", "user.email", "woodshed@example.com"], { cwd: directory });
await command(["git", "config", "commit.gpgSign", "false"], { cwd: directory });
await command(["git", "remote", "add", "origin", "git@github.com:PostHog/posthog.git"], { cwd: directory });
await Bun.write(join(directory, "AGENTS.md"), "This is an isolated Woodshed access test. The owner authorizes reading GitHub PR 130393 and preparing verified.txt for the controller to sign locally. Never push, mutate GitHub, or change another repository.\n");
const name = `ws-access-${randomUUID().slice(0, 8)}`;
const path = join(directory, "worker.json"); const model = "gpt-6.1-sol";
await Bun.write(path, JSON.stringify({ id: name, number: 0, checkout: directory, directory, resultDirectory, model, price: publishedPrices[model], prices: publishedPrices, budgetUSD: 1, startedAt: new Date().toISOString(), prompt: `Verify routine GitHub access without asking for permission: run gh api repos/PostHog/posthog/pulls/130393 --jq .number; run git remote get-url origin and git ls-remote origin HEAD. After all commands succeed create verified.txt containing 'GitHub read verified'. Do not stage, commit, push, or mutate GitHub. The controller will sign this locally. Write ${join(resultDirectory, "result.json")} with {"outcome":"ready_to_publish","files":["verified.txt"],"reason":"GitHub read verified"} only if all commands succeed, otherwise {"outcome":"needs_human","reason":"the verified failure"}. Stop.` }));
let started = false;
try {
  await command(["hc", "run", "--json", "--bg", "--no-parent", "--name", name, "--cwd", directory, ...workerCommand(config, directory, [process.execPath, join(import.meta.dir, "../src/worker.ts"), path])]); started = true;
  await command(["hc", "wait", "--json", "--timeout", "90", name], { timeout: 100_000 });
  const state = await Bun.file(join(directory, "runtime.json")).json();
  if (state.status !== "done") throw new Error(`Access smoke stopped: ${state.summary}`);
  if (!await Bun.file(join(directory, "verified.txt")).exists()) throw new Error("Agent did not prepare its declared change");
  await command(["git", "add", "--", "verified.txt"], { cwd: directory });
  await command(["git", "commit", "-m", "chore: verify Woodshed service signing"], { cwd: directory });
  const allowed = join(directory, "allowed-signers");
  await Bun.write(allowed, `woodshed@example.com ${await Bun.file(config.gitSigningKey + ".pub").text()}`);
  const env = gitEnvironment(config.gitSigningKey);
  const verification = Bun.spawn(["git", "-c", `gpg.ssh.allowedSignersFile=${allowed}`, "verify-commit", "HEAD"], { cwd: directory, env, stdout: "pipe", stderr: "pipe" });
  const output = await new Response(verification.stderr).text();
  if (await verification.exited !== 0) throw new Error(`Signature verification failed: ${output}`);
  console.log(JSON.stringify({ githubRead: true, localSignature: "verified", prompts: 0, estimatedUSD: state.costUSD, directory }));
} finally { if (started) { await command(["hc", "kill", name]); await command(["hc", "rm", name]); } }
